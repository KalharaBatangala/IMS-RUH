'use client';

import { useState, useTransition } from 'react';
import type { AssetStatus, ItemCondition } from '@prisma/client';
import Swal from 'sweetalert2';
import { getEquipmentUnits, getLabEquipmentTypes, updateEquipmentUnit } from '@/actions/equipment';
import { AvailabilityBadge } from '@/components/StatusBadge';

export type EquipmentUnit = Extract<Awaited<ReturnType<typeof getEquipmentUnits>>, { success: true }>['data'][number];
type UnitPatch = Parameters<typeof updateEquipmentUnit>[1];

function dateInput(d: Date | string | null | undefined) {
  if (!d) return '';
  const x = new Date(d);
  return `${x.getFullYear()}-${String(x.getMonth() + 1).padStart(2, '0')}-${String(x.getDate()).padStart(2, '0')}`;
}
function shortDate(d: Date | string | null | undefined) {
  return d ? new Date(d).toLocaleDateString() : '';
}

export default function UnitsPanel({
  equipment,
  labId,
  units,
  highlight,
  onChanged,
}: {
  equipment: { id: string; name: string };
  labId: string;
  units: EquipmentUnit[];
  highlight: string[];
  onChanged: () => Promise<void> | void;
}) {
  const [editing, setEditing] = useState<EquipmentUnit | null>(null);
  const [types, setTypes] = useState<{ id: string; name: string; brand: string | null; model: string | null }[]>([]);
  const [isPending, startTransition] = useTransition();

  async function apply(unit: EquipmentUnit, data: UnitPatch) {
    const unfit = (data.condition && data.condition !== 'WORKING') || data.assetStatus === 'NOT_RECEIVED' || data.archived === true;
    if (unit.status === 'RESERVED' && unfit) {
      const confirm = await Swal.fire({
        title: 'This unit is reserved',
        text: 'Making it unavailable will cancel the reservation and notify the borrower. Continue?',
        icon: 'warning',
        showCancelButton: true,
        confirmButtonText: 'Continue',
      });
      if (!confirm.isConfirmed) {
        await onChanged();
        return false;
      }
    }
    const res = await updateEquipmentUnit(unit.id, data);
    if (res.success) {
      if (res.message) Swal.fire('Updated', res.message, 'info');
    } else {
      Swal.fire('Error', res.error, 'error');
    }
    await onChanged();
    return res.success;
  }

  async function openEdit(unit: EquipmentUnit) {
    setEditing(unit);
    const res = await getLabEquipmentTypes(labId);
    if (res.success) setTypes(res.data);
  }

  function submitEdit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    if (!editing) return;
    const f = new FormData(e.currentTarget);
    const unit = editing;
    const patch: UnitPatch = {
      serialNumber: String(f.get('serialNumber') ?? ''),
      location: String(f.get('location') ?? ''),
      purchasedAt: String(f.get('purchasedAt') ?? ''),
      lastCheckedAt: String(f.get('lastCheckedAt') ?? ''),
      notes: String(f.get('notes') ?? ''),
    };
    if (unit.availability === 'UNAVAILABLE' || f.get('unavailableReason')) patch.unavailableReason = String(f.get('unavailableReason') ?? '');
    const move = String(f.get('moveTo') ?? '');
    if (move && move !== equipment.id) patch.moveToEquipmentId = move;
    startTransition(async () => {
      if (await apply(unit, patch)) setEditing(null);
    });
  }

  const input = 'w-full px-3 py-2 border rounded-lg text-sm outline-none focus:ring-2 focus:ring-blue-500';
  const label = 'block text-xs font-semibold text-slate-700 uppercase mb-1';
  const lowerHighlight = highlight.map((h) => h.toLowerCase());

  return (
    <>
      <div className="overflow-x-auto">
        <table className="w-full text-xs">
          <thead className="text-slate-500 uppercase text-[10px]">
            <tr>
              <th className="py-1 text-left">Serial / Asset Tag</th>
              <th className="py-1 text-left">Availability</th>
              <th className="py-1 text-left">Condition</th>
              <th className="py-1 text-left">Status</th>
              <th className="py-1 text-left">Location</th>
              <th className="py-1 text-left">Remarks / Reason</th>
              <th className="py-1 text-left">Checked</th>
              <th className="py-1 text-right"></th>
            </tr>
          </thead>
          <tbody>
            {units.map((u) => {
              const onLoan = u.status === 'ISSUED';
              const hit = lowerHighlight.includes(u.serialNumber.toLowerCase());
              return (
                <tr key={u.id} className={`border-t border-slate-200 align-top ${u.archived ? 'opacity-50' : ''} ${hit ? 'bg-yellow-50' : ''}`}>
                  <td className="py-1.5 font-mono pr-2">
                    {u.serialNumber}
                    {u.serialIsPlaceholder && (
                      <span className="block font-sans text-[9px] font-bold text-amber-700" title="Generated by the system — no manufacturer serial recorded">
                        GENERATED TAG
                      </span>
                    )}
                  </td>
                  <td className="py-1.5 pr-2">
                    <AvailabilityBadge availability={u.availability} />
                    {u.archived && <span className="text-[10px] font-bold text-slate-500">ARCHIVED</span>}
                    {u.holder && (
                      <span className="block text-[10px] text-slate-500">
                        {u.holder.name} · due {shortDate(u.holder.returnDate)}
                        {u.holder.status === 'OVERDUE' && <b className="text-rose-600"> · OVERDUE</b>}
                      </span>
                    )}
                  </td>
                  <td className="py-1.5 pr-2">
                    <select
                      value={u.condition}
                      disabled={onLoan}
                      title={onLoan ? 'Recorded by the TO at return' : undefined}
                      onChange={(e) => apply(u, { condition: e.target.value as ItemCondition })}
                      className="text-xs border rounded px-1 py-0.5 bg-white outline-none disabled:bg-slate-100"
                    >
                      <option value="WORKING">WORKING</option>
                      <option value="DAMAGED">DAMAGED</option>
                      <option value="UNDER_REPAIR">UNDER_REPAIR</option>
                    </select>
                  </td>
                  <td className="py-1.5 pr-2">
                    <select
                      value={u.assetStatus}
                      disabled={onLoan}
                      onChange={(e) => apply(u, { assetStatus: e.target.value as AssetStatus })}
                      className="text-xs border rounded px-1 py-0.5 bg-white outline-none disabled:bg-slate-100"
                    >
                      <option value="RECEIVED">RECEIVED</option>
                      <option value="NOT_RECEIVED">NOT_RECEIVED</option>
                    </select>
                  </td>
                  <td className="py-1.5 pr-2 text-slate-600">{u.location || <span className="text-slate-300">—</span>}</td>
                  <td className="py-1.5 pr-2 max-w-xs text-slate-600">
                    {u.notes && <div>{u.notes}</div>}
                    {u.unavailableReason && <div className="text-rose-700">⚠ {u.unavailableReason}</div>}
                    {!u.notes && !u.unavailableReason && <span className="text-slate-300">—</span>}
                  </td>
                  <td className="py-1.5 pr-2 whitespace-nowrap text-slate-500">
                    {u.lastCheckedAt ? shortDate(u.lastCheckedAt) : <span className="text-slate-300">never</span>}
                    <button
                      onClick={() => apply(u, { markCheckedToday: true })}
                      className="ml-1 text-[10px] text-emerald-700 hover:underline"
                      title="Record that this unit was physically verified today"
                    >
                      ✓ today
                    </button>
                  </td>
                  <td className="py-1.5 text-right whitespace-nowrap space-x-2">
                    <button onClick={() => openEdit(u)} className="text-[11px] text-blue-600 font-semibold hover:underline">
                      Edit
                    </button>
                    {!onLoan && (
                      <button onClick={() => apply(u, { archived: !u.archived })} className="text-[10px] text-slate-500 hover:underline">
                        {u.archived ? 'Restore' : 'Archive'}
                      </button>
                    )}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      {editing && (
        <div className="fixed inset-0 bg-slate-900/40 backdrop-blur-sm flex items-center justify-center p-4 z-50">
          <form onSubmit={submitEdit} className="bg-white rounded-2xl p-6 w-full max-w-lg shadow-2xl space-y-3 max-h-[90vh] overflow-y-auto">
            <div>
              <h2 className="text-lg font-bold text-slate-900">Edit unit</h2>
              <p className="text-xs text-slate-500">{equipment.name} · changes are recorded in the audit log</p>
            </div>
            <div>
              <label className={label}>Serial number / asset tag *</label>
              <input name="serialNumber" required defaultValue={editing.serialNumber} className={`${input} font-mono`} />
              <p className="text-[10px] text-slate-400 mt-1">
                {editing.serialIsPlaceholder
                  ? 'This is a generated tag. Replace it with the manufacturer serial if the item has one; otherwise keep it and label the item with it.'
                  : 'Correct typing mistakes here. The old value is kept in the audit log.'}
              </p>
            </div>
            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className={label}>Current location</label>
                <input name="location" defaultValue={editing.location ?? ''} placeholder="e.g. Stores Room" className={input} />
              </div>
              <div>
                <label className={label}>Date of purchase</label>
                <input name="purchasedAt" type="date" defaultValue={dateInput(editing.purchasedAt)} className={input} />
              </div>
            </div>
            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className={label}>Last checked</label>
                <input name="lastCheckedAt" type="date" defaultValue={dateInput(editing.lastCheckedAt)} className={input} />
              </div>
              <div>
                <label className={label}>Equipment type</label>
                <select
                  name="moveTo"
                  defaultValue={equipment.id}
                  disabled={editing.status !== 'AVAILABLE'}
                  title={editing.status !== 'AVAILABLE' ? 'Reserved / issued units cannot be moved' : undefined}
                  className={`${input} bg-white disabled:bg-slate-100`}
                >
                  {(types.length ? types : [{ id: equipment.id, name: equipment.name, brand: null, model: null }]).map((t) => (
                    <option key={t.id} value={t.id}>
                      {t.name}
                      {t.brand || t.model ? ` (${[t.brand, t.model].filter(Boolean).join(' / ')})` : ''}
                    </option>
                  ))}
                </select>
              </div>
            </div>
            <div>
              <label className={label}>Remarks</label>
              <textarea name="notes" rows={2} defaultValue={editing.notes ?? ''} placeholder="e.g. Kept in HPC room; includes power adapter" className={input} />
            </div>
            <div>
              <label className={label}>Unavailable reason {editing.availability !== 'UNAVAILABLE' && '(only shown while unavailable)'}</label>
              <textarea
                name="unavailableReason"
                rows={2}
                defaultValue={editing.unavailableReason ?? ''}
                placeholder="e.g. Sent for calibration on 2026-10-01"
                className={input}
              />
            </div>
            <div className="flex justify-end gap-2 pt-2">
              <button type="button" onClick={() => setEditing(null)} className="px-4 py-2 border rounded-lg text-sm text-slate-600 hover:bg-slate-50">
                Cancel
              </button>
              <button type="submit" disabled={isPending} className="px-4 py-2 bg-blue-600 text-white text-sm font-medium rounded-lg hover:bg-blue-700 disabled:opacity-50">
                {isPending ? 'Saving...' : 'Save unit'}
              </button>
            </div>
          </form>
        </div>
      )}
    </>
  );
}
